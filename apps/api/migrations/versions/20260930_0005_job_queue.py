FUNCTIONS = r"""
-- Exponential backoff with equal jitter: half fixed, half random, so the jobs a provider
-- outage failed together do not all come back in the same second.
CREATE FUNCTION jobq_backoff(p_attempts integer, p_base_seconds integer, p_cap_seconds integer)
RETURNS interval LANGUAGE sql VOLATILE AS $$
    SELECT make_interval(secs => d / 2 + random() * d / 2)
    FROM (
        SELECT least(p_cap_seconds, p_base_seconds * power(2, greatest(p_attempts - 1, 0)))::float8
    ) AS s (d)
$$;

CREATE FUNCTION jobq_enqueue(
    p_org bigint,
    p_kind text,
    p_payload jsonb,
    p_dedupe_key text DEFAULT NULL,
    p_priority smallint DEFAULT 0,
    p_max_attempts integer DEFAULT 5,
    p_budget_usd numeric DEFAULT NULL,
    p_parent_id bigint DEFAULT NULL,
    p_run_after timestamptz DEFAULT now()
) RETURNS TABLE (job_id bigint, created boolean) LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE
    v_id bigint;
BEGIN
    -- Two tries: the job holding the key can fail between the conflict and the lookup,
    -- which frees the key for this insert.
    FOR i IN 1..2 LOOP
        INSERT INTO jobs (org_id, kind, payload, dedupe_key, priority, max_attempts,
                          budget_usd, parent_id, run_after)
        VALUES (p_org, p_kind, p_payload, p_dedupe_key, p_priority, p_max_attempts,
                p_budget_usd, p_parent_id, p_run_after)
        ON CONFLICT (org_id, kind, dedupe_key)
            WHERE dedupe_key IS NOT NULL AND status IN ('queued', 'running', 'succeeded')
            DO NOTHING
        RETURNING id INTO v_id;
        IF v_id IS NOT NULL THEN
            PERFORM pg_notify('jobq', p_kind);
            RETURN QUERY SELECT v_id, true;
            RETURN;
        END IF;
        SELECT id INTO v_id FROM jobs
        WHERE org_id = p_org AND kind = p_kind AND dedupe_key = p_dedupe_key
          AND status IN ('queued', 'running', 'succeeded');
        IF v_id IS NOT NULL THEN
            RETURN QUERY SELECT v_id, false;
            RETURN;
        END IF;
    END LOOP;
    RAISE EXCEPTION 'jobq_enqueue: could not insert or find % %', p_kind, p_dedupe_key;
END
$$;

-- The oldest ready job of the given kinds, highest priority first. SKIP LOCKED lets any
-- number of workers claim at once without waiting on each other's row locks.
CREATE FUNCTION jobq_claim(p_worker text, p_kinds text[], p_lease_seconds integer)
RETURNS SETOF jobs LANGUAGE sql AS $$
    UPDATE jobs AS j
    SET status = 'running',
        attempts = j.attempts + 1,
        locked_by = p_worker,
        lease_until = now() + make_interval(secs => p_lease_seconds),
        heartbeat_at = now(),
        started_at = coalesce(j.started_at, now()),
        updated_at = now()
    WHERE j.id = (
        SELECT id FROM jobs
        WHERE status = 'queued' AND kind = ANY (p_kinds) AND run_after <= now()
        ORDER BY priority DESC, run_after, id
        FOR UPDATE SKIP LOCKED
        LIMIT 1
    )
    RETURNING j.*
$$;

-- 'ok', 'cancel' (someone asked to stop: finish with jobq_fail) or 'lost' (the lease expired
-- and the job was reaped or taken; stop without writing anything).
CREATE FUNCTION jobq_heartbeat(
    p_job bigint, p_worker text, p_lease_seconds integer, p_progress jsonb DEFAULT NULL
) RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    v_cancel boolean;
BEGIN
    UPDATE jobs
    SET lease_until = now() + make_interval(secs => p_lease_seconds),
        heartbeat_at = now(),
        progress = coalesce(p_progress, progress),
        updated_at = now()
    WHERE id = p_job AND status = 'running' AND locked_by = p_worker
    RETURNING cancel_requested INTO v_cancel;
    IF NOT FOUND THEN
        RETURN 'lost';
    END IF;
    RETURN CASE WHEN v_cancel THEN 'cancel' ELSE 'ok' END;
END
$$;

CREATE FUNCTION jobq_complete(
    p_job bigint, p_worker text, p_result jsonb, p_cost jsonb DEFAULT '{}'
) RETURNS boolean LANGUAGE sql AS $$
    WITH done AS (
        UPDATE jobs
        SET status = 'succeeded', result = p_result, cost = p_cost, error = NULL,
            locked_by = NULL, lease_until = NULL, finished_at = now(), updated_at = now()
        WHERE id = p_job AND status = 'running' AND locked_by = p_worker
        RETURNING id
    )
    SELECT EXISTS (SELECT 1 FROM done)
$$;

-- 'retry' (queued again after a backoff), 'failed', 'cancelled', or 'lost'.
CREATE FUNCTION jobq_fail(
    p_job bigint,
    p_worker text,
    p_error text,
    p_retryable boolean,
    p_base_seconds integer DEFAULT 15,
    p_cap_seconds integer DEFAULT 3600,
    p_cost jsonb DEFAULT NULL
) RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    j jobs;
    v_outcome text;
BEGIN
    SELECT * INTO j FROM jobs
    WHERE id = p_job AND status = 'running' AND locked_by = p_worker
    FOR UPDATE;
    IF NOT FOUND THEN
        RETURN 'lost';
    END IF;
    v_outcome := CASE
        WHEN j.cancel_requested THEN 'cancelled'
        WHEN p_retryable AND j.attempts < j.max_attempts THEN 'retry'
        ELSE 'failed'
    END;
    UPDATE jobs
    SET status = CASE v_outcome WHEN 'retry' THEN 'queued' ELSE v_outcome END,
        run_after = CASE v_outcome
            WHEN 'retry' THEN now() + jobq_backoff(j.attempts, p_base_seconds, p_cap_seconds)
            ELSE run_after
        END,
        finished_at = CASE v_outcome WHEN 'retry' THEN NULL ELSE now() END,
        error = p_error,
        cost = coalesce(p_cost, cost),
        locked_by = NULL,
        lease_until = NULL,
        updated_at = now()
    WHERE id = p_job;
    RETURN v_outcome;
END
$$;

-- Jobs whose worker stopped heartbeating (killed, OOM, network partition) go back to the
-- queue with a backoff, or fail once they have used their attempts.
CREATE FUNCTION jobq_reap(p_base_seconds integer DEFAULT 15, p_cap_seconds integer DEFAULT 3600)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    n integer;
BEGIN
    WITH expired AS (
        SELECT id FROM jobs
        WHERE status = 'running' AND lease_until < now()
        FOR UPDATE SKIP LOCKED
    )
    UPDATE jobs AS j
    SET status = CASE
            WHEN j.cancel_requested THEN 'cancelled'
            WHEN j.attempts < j.max_attempts THEN 'queued'
            ELSE 'failed'
        END,
        run_after = CASE
            WHEN NOT j.cancel_requested AND j.attempts < j.max_attempts
            THEN now() + jobq_backoff(j.attempts, p_base_seconds, p_cap_seconds)
            ELSE j.run_after
        END,
        finished_at = CASE
            WHEN j.cancel_requested OR j.attempts >= j.max_attempts THEN now()
        END,
        error = 'lease expired: ' || j.locked_by || ' stopped heartbeating',
        locked_by = NULL,
        lease_until = NULL,
        updated_at = now()
    FROM expired
    WHERE j.id = expired.id;
    GET DIAGNOSTICS n = ROW_COUNT;
    RETURN n;
END
$$;

-- Cancels the job and everything under it: queued jobs at once, running ones at their next
-- heartbeat. Under row-level security another tenant's job is simply 'not_found'.
CREATE FUNCTION jobq_cancel(p_job bigint) RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    v_status text;
BEGIN
    WITH RECURSIVE tree AS (
        SELECT id FROM jobs WHERE id = p_job
        UNION ALL
        SELECT c.id FROM jobs AS c JOIN tree AS t ON c.parent_id = t.id
    ),
    queued AS (
        UPDATE jobs SET status = 'cancelled', finished_at = now(), updated_at = now()
        WHERE id IN (SELECT id FROM tree) AND status = 'queued'
        RETURNING id
    )
    UPDATE jobs SET cancel_requested = true, updated_at = now()
    WHERE id IN (SELECT id FROM tree) AND status = 'running';
    SELECT status INTO v_status FROM jobs WHERE id = p_job;
    RETURN CASE
        WHEN v_status IS NULL THEN 'not_found'
        WHEN v_status = 'running' THEN 'cancelling'
        ELSE v_status
    END;
END
$$;
"""

