def _statements(sql: str) -> list[str]:
    """One statement per execute (asyncpg prepares each); ``$$`` bodies keep their ``;``."""
    out: list[str] = []
    buf: list[str] = []
    quoted = False
    for line in sql.splitlines():
        buf.append(line)
        quoted ^= line.count("$$") % 2 == 1
        if not quoted and line.rstrip().endswith(";"):
            out.append("\n".join(buf).strip())
            buf = []
    if "\n".join(buf).strip():
        out.append("\n".join(buf).strip())
    return out


